const FALLBACK = 0.7;
const WIDE = 1;

const table = new Map();
for (const [start, widths] of RUNS) widths.split(",").forEach((w, i) => table.set(start + i, Number(w) / 1000));

const isWide = (c) => (c >= 0x1100 && c <= 0x115f) || (c >= 0x2e80 && c <= 0xa4cf) || (c >= 0xac00 && c <= 0xd7a3) || (c >= 0xf900 && c <= 0xfaff)
  || (c >= 0xfe30 && c <= 0xfe6f) || (c >= 0xff00 && c <= 0xff60) || (c >= 0xffe0 && c <= 0xffe6) || (c >= 0x1f300 && c <= 0x1faff);

/** Width of one line of text, in pixels, at this font size. */
export function lineWidth(line, fontSize) {
  let em = 0;
  for (const ch of String(line)) {
    const c = ch.codePointAt(0);
    em += table.get(c) ?? (isWide(c) ? WIDE : FALLBACK);
  }
  return em * fontSize;
}
